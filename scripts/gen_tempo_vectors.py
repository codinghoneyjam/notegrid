#!/usr/bin/env python3
# <META - FILE SUMMARY - Reference generator for R02.AC2: exact-rational tempo->sample positions written as a schedule-shaped JSON fixture.>
"""Generate the tempo-change golden fixtures that R02.AC2 compares against.

R02.AC2 asks for "an independent exact-rational computation (fixtures generated by a Python
fractions script)". This is that script. It is deliberately NOT part of ng-timeline: it is
the second opinion, so sharing code with the implementation would defeat the point. It is
also outside T1.1's SCOPE (crates/ng-timeline/**), which is why it lives in scripts/ and why
the T1.1 acceptance test treats the emitted JSON as an input fixture rather than producing it.

Usage:  python scripts/gen_tempo_vectors.py            # writes spec/fixture/tempo/*.json
        python scripts/gen_tempo_vectors.py --check    # verify committed files are current

The arithmetic is Python's fractions.Fraction with no floating point anywhere:
    mpq   = round_half_up(60_000_000 / bpm)          # exact, bpm is a rational here
    T(t)  = sum over segments of delta_tick * mpq     # integer microseconds
    s(t)  = round_half_up(T(t) * sr / (480 * 1e6))   # C0.3, rounded once at the end
"""

import json
import pathlib
import sys
from fractions import Fraction

PPQ = 480
MICROS_PER_QUARTER = 1_000_000
OUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "spec" / "fixture" / "tempo"

SAMPLE_RATES = (44100, 48000)


def round_half_up(value: Fraction) -> int:
    """C0.3 rounding: ties go up. Works for negatives too, which floor(x + 1/2) does not."""
    return (value + Fraction(1, 2)).numerator // (value + Fraction(1, 2)).denominator


def mpq_of(bpm: Fraction) -> int:
    """C0.2: mpq = round_half_up(60_000_000 / bpm)."""
    return round_half_up(Fraction(60_000_000) / bpm)


def sample_of_tick(tick: int, tempo: list[dict], sr: int) -> int:
    """C0.3: accumulate delta_tick * mpq as exact integers, convert once at the end."""
    if tick < 0:
        raise ValueError("tick must be >= 0")
    if not tempo:
        raise ValueError("tempo list must not be empty")
    if tempo[0]["tick"] != 0:
        raise ValueError("tempo[0].tick must be 0")

    micros = 0
    for i, change in enumerate(tempo):
        start_tick = change["tick"]
        if i + 1 < len(tempo):
            end_tick = tempo[i + 1]["tick"]
        else:
            end_tick = tick
        if start_tick > tick:
            break
        covered_end = min(end_tick, tick)
        if covered_end > start_tick:
            micros += (covered_end - start_tick) * mpq_of(Fraction(str(change["bpm"])))
    return round_half_up(Fraction(micros * sr, PPQ * MICROS_PER_QUARTER))


def probe_ticks(tempo: list[dict], last_tick: int) -> list[int]:
    """Every change point, plus its neighbours, plus the ends. Change points are where the
    rounding of a per-segment implementation would show up, so they carry the signal."""
    ticks = {0, last_tick}
    for change in tempo:
        t = change["tick"]
        ticks.update({t - 1, t, t + 1})
    return sorted(t for t in ticks if 0 <= t <= last_tick)


CASES = {
    "single_124bpm": {
        "tempo": [{"tick": 0, "bpm": 124.0}],
        "last_tick": 7680,
    },
    "two_changes": {
        "tempo": [
            {"tick": 0, "bpm": 120.0},
            {"tick": 1920, "bpm": 90.0},
            {"tick": 4800, "bpm": 150.0},
        ],
        "last_tick": 7680,
    },
    "change_on_bar_boundary": {
        "tempo": [
            {"tick": 0, "bpm": 100.0},
            {"tick": 3840, "bpm": 175.0},
        ],
        "last_tick": 7680,
    },
    "slow_to_fast_extremes": {
        "tempo": [
            {"tick": 0, "bpm": 20.0},
            {"tick": 960, "bpm": 400.0},
            {"tick": 3360, "bpm": 20.5},
        ],
        "last_tick": 7680,
    },
    "late_single_change": {
        "tempo": [{"tick": 0, "bpm": 132.0}, {"tick": 7200, "bpm": 68.0}],
        "last_tick": 7680,
    },
}


def build(name: str, case: dict) -> dict:
    tempo = case["tempo"]
    return {
        "case": name,
        "ppq": PPQ,
        "tempo": tempo,
        "last_tick": case["last_tick"],
        "expected": {
            str(sr): {
                str(tick): sample_of_tick(tick, tempo, sr)
                for tick in probe_ticks(tempo, case["last_tick"])
            }
            for sr in SAMPLE_RATES
        },
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    stale = []

    for name, case in sorted(CASES.items()):
        payload = build(name, case)
        text = json.dumps(payload, indent=2, sort_keys=True) + "\n"
        path = OUT_DIR / f"{name}.json"
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(OUT_DIR.parent.parent.parent)}")

    if check:
        if stale:
            print("tempo vectors are stale, re-run without --check: " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"tempo vectors current ({len(CASES)} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
